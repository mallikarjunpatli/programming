package programming;

import java.util.HashSet;

public class HashSetExample {


		public static void main(String arg[]) {
			
			HashSet set=new HashSet();
			
			set.add(20);
			set.add(48.5);
			set.add("malli");
			set.add(39.3f);
			set.add('m');
			set.add('1');
			
			System.out.println(set);
		}

	}



